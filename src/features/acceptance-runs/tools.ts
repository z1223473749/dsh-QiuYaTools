import type { Context } from '@deepseek-ai/cordis'
import type { RunJsonSchema as JsonSchemaNode, RunToolDefinition as ToolDefinition, RunToolsService } from './sdk-host-seams.ts'
import type { JsonValue } from '@deepseek-ai/dsh-util-values'
import { canonicalJSON, object, parseBegin, parseCheckpoint, parseMutation, RunError, uuid, RUN_STATES, VERIFY_CODES } from './contract.ts'
import type { CheckPlan } from './contract.ts'
import type { AcceptanceRunService, MutationResult, RunExec } from './service.ts'
import { parseRunMeta, parseRunSummary, runToolValue, viewFromMutation, RUN_STATE_LABELS } from './model.ts'
import type { RunToolName } from './model.ts'

export interface AcceptanceToolsOptions {
  enabled?(): boolean
  verifierForCheck?(check: Readonly<Omit<CheckPlan, 'verifierId'>>): string | null
  onBegin?(exec: RunExec, result: MutationResult): Promise<MutationResult>
}

const safeJSON = (value: unknown): JsonValue => JSON.parse(canonicalJSON(value)) as JsonValue
const id: JsonSchemaNode = { type: 'string', description: 'Lowercase UUID generated by the Host.' }
const mutation: Record<string, JsonSchemaNode> = {
  runId: id,
  expectedRevision: { type: 'integer', description: 'The current committed revision, from 1 through 128.' },
  idempotencyKey: { type: 'string', description: 'A new stable operation key; up to 96 letters, digits, underscore, dot, colon or hyphen.' },
}
const nullable = (schema: JsonSchemaNode): JsonSchemaNode => ({ oneOf: [schema, { type: 'null' }] })
const summaryProperties: Record<string, JsonSchemaNode> = {
  runId: id, chatSessionId: { type: 'string' }, revision: { type: 'integer' }, title: { type: 'string' },
  state: { type: 'string', enum: [...RUN_STATES] }, requiredPassed: { type: 'integer' }, requiredTotal: { type: 'integer' },
  evidenceCount: { type: 'integer' }, attemptCount: { type: 'integer' }, createdAt: { type: 'integer' }, updatedAt: { type: 'integer' },
  endedAt: nullable({ type: 'integer' }), readOnly: { type: 'boolean' },
  recovery: { type: 'string', enum: ['none', 'restart-interrupted', 'evidence-unavailable', 'historical'] },
}
const outputSchema: JsonSchemaNode = {
  type: 'object', additionalProperties: false, required: ['run', 'checks'], properties: {
    run: { type: 'object', additionalProperties: false, required: Object.keys(summaryProperties), properties: summaryProperties },
    checks: { type: 'array', items: {
      type: 'object', additionalProperties: false, required: ['checkId', 'title', 'expected', 'required', 'attempts'], properties: {
        checkId: { type: 'string' }, title: { type: 'string' }, expected: { type: 'string' }, required: { type: 'boolean' },
        attempts: { type: 'array', items: {
          type: 'object', additionalProperties: false, required: ['attemptId', 'verdict', 'verificationCode', 'evidenceIds', 'committedEvidenceIds'], properties: {
            attemptId: id, verdict: nullable({ type: 'string', enum: ['passed', 'failed', 'blocked', 'inconclusive'] }),
            verificationCode: nullable({ type: 'string', enum: [...VERIFY_CODES] }), evidenceIds: { type: 'array', items: id }, committedEvidenceIds: { type: 'array', items: id, description: 'All Host-committed evidence for this attempt, available even before assessment.' },
          },
        } },
      },
    } },
  },
}
const errors: Record<string, string> = {
  CALLER_NOT_LIVE: '当前会话已变化，请重新发起任务。', OWNER_CHANGED: '操作环境或控制权已变化，请重新观察。',
  REVISION_CONFLICT: '任务记录已更新，请先读取最新记录。', HISTORY_READ_ONLY: '这份记录仅供查看，请新建任务继续。',
  RUN_NOT_RUNNING: '任务尚未进入执行状态。', RUN_NOT_FOUND: '当前会话没有这份任务记录。',
  EVIDENCE_UNAVAILABLE: '证据暂不可用，结果保持待确认。', EVIDENCE_BINDING_MISMATCH: '证据不属于当前任务检查点。',
  INVALID_REQUEST: '任务参数无效。',
}
function publicError(error: unknown, exec: RunExec): Error {
  const code = exec.signal.aborted ? 'RUN_CANCELLED'
    : error instanceof RunError && /^[A-Z_]{3,64}$/u.test(error.code) ? error.code : 'RUN_UNAVAILABLE'
  return new Error(`[${code}] ${errors[code] ?? '任务记录未能完成，请核对最新状态；不要重放未确认的操作。'}`)
}

/** Public schema subset plus strict core parsing. No new Agent, model loop or control channel. */
export function installAcceptanceRunTools(ctx: Context, service: AcceptanceRunService, options: AcceptanceToolsOptions = {}): () => void {
  const runtime = ctx as Context & { tools: RunToolsService }
  const definitions: ToolDefinition[] = []
  const titles: Record<RunToolName, string> = {
    qiuya_run_begin: '建立任务记录', qiuya_run_get: '读取任务记录',
    qiuya_run_checkpoint: '记录验收检查点', qiuya_run_finish: '汇总验收结果',
  }
  const define = (name: RunToolName, parameters: ToolDefinition['parameters'], description: string, execute: ToolDefinition['execute']) => {
    definitions.push({
      name, description, parameters,
      output: {
        schema: outputSchema,
        render: (_args, value) => [{ type: 'text', text: canonicalJSON(value) }],
        presentationMeta(_args, value) {
          const v = object(value, ['run', 'checks'])
          return safeJSON({ kind: 'qiuya-run', version: 1, tool: name, run: parseRunSummary(v.run) })
        },
      },
      presentCall: () => ({ card: 'generic', title: titles[name], kind: name === 'qiuya_run_get' ? 'read' : 'other' }),
      presentResult(_args, result) {
        if (result.isError) return undefined
        const meta = parseRunMeta(result.meta)
        return meta ? { card: 'generic', title: `${meta.run.title} · ${RUN_STATE_LABELS[meta.run.state]}` } : undefined
      },
      async execute(args, exec) {
        try {
          if (options.enabled?.() === false) throw new RunError('RUN_DISABLED')
          return await execute(args, exec)
        } catch (error) { throw publicError(error, exec) }
      },
    })
  }
  define('qiuya_run_begin', {
    type: 'object', additionalProperties: false, required: ['title', 'checks', 'budget', 'idempotencyKey', 'previousRunId'], properties: {
      title: { type: 'string', description: 'Task title, up to 160 characters.' },
      checks: { type: 'array', description: 'Up to 32 frozen checks. No model-selected verifier.', items: {
        type: 'object', additionalProperties: false, required: ['checkId', 'title', 'expected', 'required', 'minimumEvidence'], properties: {
          checkId: { type: 'string' }, title: { type: 'string' }, expected: { type: 'string' }, required: { type: 'boolean' },
          minimumEvidence: { type: 'integer', description: 'One through eight real committed observations.' },
        },
      } },
      budget: { type: 'object', additionalProperties: false, required: ['maxAttempts', 'maxActions', 'maxEvidence', 'deadlineMs'], properties: {
        maxAttempts: { type: 'integer', description: '1 through 64.' }, maxActions: { type: 'integer', description: '1 through 128.' },
        maxEvidence: { type: 'integer', description: '1 through 64.' }, deadlineMs: { type: 'integer', description: '1000 through 3600000.' },
      } },
      idempotencyKey: mutation.idempotencyKey, previousRunId: nullable(id),
    },
  }, 'Begin an acceptance record in this live root Agent’s existing authorized computer environment. Freeze checks. No chat, environment, authority or verifier selection. The record grants no control and performs no action. Start one checkpoint attempt before observe/act. Observe returns a committed evidenceId and current revision; get recovers committedEvidenceIds without recapturing. Model assessments cannot decide final passed.', async (args, exec) => {
    const v = object(args, ['title', 'checks', 'budget', 'idempotencyKey', 'previousRunId'])
    if (!Array.isArray(v.checks) || v.checks.length > 32) throw new RunError('INVALID_REQUEST')
    // Validate the entire bounded input before calling any trusted verifier resolver.
    const parsed = parseBegin({ ...v, checks: v.checks.map(raw => ({ ...object(raw, ['checkId', 'title', 'expected', 'required', 'minimumEvidence']), verifierId: null })) })
    const checks = parsed.checks.map(({ verifierId: _ignored, ...check }) => ({
      ...check, verifierId: options.verifierForCheck?.(Object.freeze(check)) ?? null,
    }))
    let result = await service.begin(exec, { ...parsed, checks })
    if (options.onBegin && !result.replayed) result = await options.onBegin(exec, result)
    return safeJSON(runToolValue(viewFromMutation(result)))
  })
  define('qiuya_run_get', {
    type: 'object', additionalProperties: false, required: ['runId'], properties: { runId: id },
  }, 'Read this Agent’s own run, current revision, check attempts and evidence IDs. Historical reads never resume control or replay input.', async (args, exec) => {
    const v = object(args, ['runId'])
    return safeJSON(runToolValue(await service.get(exec, uuid(v.runId))))
  })
  define('qiuya_run_checkpoint', {
    type: 'object', additionalProperties: false, required: ['runId', 'expectedRevision', 'idempotencyKey', 'phase', 'checkId'], properties: {
      ...mutation, phase: { type: 'string', enum: ['start', 'verify'] }, checkId: { type: 'string' }, attemptId: id,
      evidenceIds: { type: 'array', items: id, description: 'Up to eight evidence IDs already committed by the Host recorder.' },
      assessment: { type: 'object', additionalProperties: false, required: ['proposal', 'summaryCode'], properties: {
        proposal: { type: 'string', enum: ['passed', 'failed', 'blocked', 'inconclusive'] },
        summaryCode: { type: 'string', enum: ['EXPECTATION_MET', 'EXPECTATION_NOT_MET', 'NEEDS_EVIDENCE', 'ENVIRONMENT_BLOCKED'] },
      } },
    },
  }, 'Start a check attempt or submit a model assessment with evidence IDs from the trusted observe recorder. No file, URL or verifier identity. A passed proposal remains inconclusive unless an independent registered verifier confirms it.', async (args, exec) =>
    safeJSON(runToolValue(viewFromMutation(await service.checkpoint(exec, parseCheckpoint(args))))))
  define('qiuya_run_finish', {
    type: 'object', additionalProperties: false, required: Object.keys(mutation), properties: mutation,
  }, 'Finish by Host aggregation of required independent verdicts and available committed evidence. No final-state argument. Missing evidence, unknown actions and model self-assessment cannot become passed.', async (args, exec) =>
    safeJSON(runToolValue(viewFromMutation(await service.finish(exec, parseMutation(args))))))
  const disposers: Array<() => void> = []
  try { for (const definition of definitions) disposers.push(runtime.tools.register(definition)) }
  catch (error) { for (const dispose of disposers.reverse()) dispose(); throw error }
  return () => { for (const dispose of disposers.splice(0).reverse()) dispose() }
}
