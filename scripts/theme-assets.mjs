import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'

const root = new URL('../', import.meta.url)
const originals = {
  garo: { scene: 'q-garo-scene.jpg', sidebar: 'q-garo-sidebar.jpg' },
  fox: { scene: 'q-fox-scene.jpg', sidebar: 'q-fox-sidebar.jpg' },
  ocean: { scene: 'q-ocean-scene.webp', plate: 'q-ocean-clean-plate.jpg' },
  begonia: { scene: 'q-begonia-scene.jpg' },
  sunset: { scene: 'q-sunset-scene.jpg' },
  moonfrost: { scene: 'q-moonfrost-scene.jpg', plate: 'q-moonfrost-clean-plate.jpg' },
  buliangren: { scene: 'q-buliangren-scene.jpg', plate: 'q-buliangren-clean-plate.jpg' },
}
const release = 'https://github.com/z1223473749/dsh-QiuYaTools/releases/download/theme-art-v1/'
const mime = file => file.endsWith('.webp') ? 'image/webp' : file.endsWith('.png') ? 'image/png' : 'image/jpeg'
const generated = '// Generated by scripts/theme-assets.mjs.\n'
const files = {}, covers = {
  MONO_ICON: 'icon-menu.png',
  COLOR_ICON: 'icon-color.webp',
}

for (const [theme, parts] of Object.entries(originals)) {
  for (const [part, file] of Object.entries(parts)) {
    const bytes = await readFile(new URL('assets/' + file, root))
    files[file] = { url: release + file, mime: mime(file), bytes: bytes.length, sha256: createHash('sha256').update(bytes).digest('hex') }
    if (part !== 'plate') covers[theme.toUpperCase() + '_' + part.toUpperCase()] = 'theme-covers/' + file.replace(/\.webp$/, '.jpg')
  }
}

const exports = await Promise.all(Object.entries(covers).map(async ([name, file]) => {
  const bytes = await readFile(new URL('assets/' + file, root))
  return `export const ${name}_DATA_URL: string = ${JSON.stringify(`data:${mime(file)};base64,${bytes.toString('base64')}`)}\n`
}))

await Promise.all([
  writeFile(new URL('src/client/brand-assets.ts', root), generated + exports.join('')),
  writeFile(new URL('src/theme-art.ts', root), generated +
    "export const THEME_ART_CHANNEL = '/api'\nexport const THEME_ART_METHOD = 'qiuya-tools/theme-art/get'\n\n" +
    `export const THEME_ART_FILES = ${JSON.stringify(files, null, 2)} as const\n\n` +
    `export const THEME_ART_PRESETS = ${JSON.stringify(originals, null, 2)} as const\n`),
])
