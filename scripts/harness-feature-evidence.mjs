/** Test-only result oracles for an explicitly bound disposable Harness profile. */
import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'

const validId = value => typeof value === 'string' && /^[A-Za-z0-9][A-Za-z0-9:_.-]{0,159}$/u.test(value)
const idList = value => Array.isArray(value) && value.length <= 512 && value.every(validId) && new Set(value).size === value.length
const signature = value => createHash('sha256').update(value).digest('hex')
const equalSet = (a, b) => a.length === b.length && a.every(id => b.includes(id))

/** Exact Chinese fixture text generated by the shipping revision composer. */
export function fixturePlanRevisionText(quote, note) {
  assert.ok(typeof quote === 'string' && quote.trim() && typeof note === 'string' && note.trim())
  return `请根据以下计划批注修正：\n\n1. “${quote}”\n   修改意见：${note}`
}

export function projectHarnessArchiveSnapshot(workspace, archivedSessionIds, binding) {
  assert.ok(validId(binding?.workspaceId) && workspace?.id === binding.workspaceId && workspace.path === binding.workspacePath, 'The exact own fixture workspace is unavailable')
  assert.ok(idList(workspace.sessionIds) && idList(archivedSessionIds) && idList(binding.selectedSessionIds) && binding.selectedSessionIds.length > 0 && idList(binding.preservedSessionIds) && binding.preservedSessionIds.length > 0, 'Fixture archive identities are invalid')
  const all = [...binding.selectedSessionIds, ...binding.preservedSessionIds]
  assert.equal(new Set(all).size, all.length, 'Archive and preserved identities must be distinct')
  return { workspaceId: binding.workspaceId, selectedSessionIds: [...binding.selectedSessionIds], preservedSessionIds: [...binding.preservedSessionIds],
    memberSessionIds: [...workspace.sessionIds], archivedSessionIds: [...archivedSessionIds] }
}

export function archiveCollectionEvidence(before, after) {
  const valid = value => value && validId(value.workspaceId) && idList(value.selectedSessionIds) && value.selectedSessionIds.length > 0 && idList(value.preservedSessionIds) && value.preservedSessionIds.length > 0 && idList(value.memberSessionIds) && idList(value.archivedSessionIds)
  if (!valid(before) || !valid(after) || before.workspaceId !== after.workspaceId || !equalSet(before.selectedSessionIds, after.selectedSessionIds) || !equalSet(before.preservedSessionIds, after.preservedSessionIds)) return { passed: false, reason: 'fixture-identity-changed' }
  const selected = before.selectedSessionIds, preserved = before.preservedSessionIds, all = [...selected, ...preserved]
  const distinct = new Set(all).size === all.length
  const beforeActive = all.every(id => before.memberSessionIds.includes(id) && !before.archivedSessionIds.includes(id))
  const expected = [...before.archivedSessionIds, ...selected]
  const exactArchiveSet = equalSet(after.archivedSessionIds, expected)
  const alphaPreserved = preserved.every(id => after.memberSessionIds.includes(id) && !after.archivedSessionIds.includes(id))
  // The public registry preserves accounting positions even when archived.
  const accountingPreserved = equalSet(before.memberSessionIds, after.memberSessionIds)
  return { passed: distinct && beforeActive && exactArchiveSet && alphaPreserved && accountingPreserved, distinct, beforeActive, exactArchiveSet, alphaPreserved, accountingPreserved,
    selectedSessionIds: selected, preservedSessionIds: preserved, addedArchivedSessionIds: after.archivedSessionIds.filter(id => !before.archivedSessionIds.includes(id)), removedArchivedSessionIds: before.archivedSessionIds.filter(id => !after.archivedSessionIds.includes(id)) }
}

/** Only ordinary durable user/message events count; no tool/assistant/queue text. */
export function projectHarnessPlanSnapshot(surface, binding) {
  const plan = binding?.plan
  assert.ok(validId(plan?.sessionId) && surface?.session?.id === plan.sessionId, 'The exact own plan session is unavailable')
  assert.ok(typeof plan.expectedText === 'string' && plan.expectedText.length > 0 && plan.expectedText.length <= 16000 && typeof plan.quote === 'string' && plan.quote && typeof plan.note === 'string' && plan.note && plan.expectedText.includes(plan.quote) && plan.expectedText.includes(plan.note), 'The exact fixture revision text is not bound')
  const capturedThroughSeq = surface.capturedThroughSeq === null ? -1 : surface.capturedThroughSeq
  assert.ok(Number.isSafeInteger(capturedThroughSeq) && capturedThroughSeq >= -1 && Array.isArray(surface.events) && surface.events.length <= 10000, 'The current model-surface event cut is unavailable')
  const matchingUserMessages = [], seen = new Set()
  for (const event of surface.events) {
    if (event?.type !== 'user/message' || event.data?.source?.kind !== 'user') continue
    assert.ok(Number.isSafeInteger(event.seq) && event.seq >= 0 && event.seq <= capturedThroughSeq && !seen.has(event.seq), 'Invalid ordinary user-message sequence')
    seen.add(event.seq)
    assert.ok(Array.isArray(event.data.content), 'Ordinary user-message content is unavailable')
    const blocks = event.data.content.filter(block => block?.type === 'text')
    assert.ok(blocks.every(block => typeof block.text === 'string'), 'Ordinary user-message text is invalid')
    const text = blocks.map(block => block.text).join('\n')
    if (text === plan.expectedText) matchingUserMessages.push({ seq: event.seq, type: 'user/message', sourceKind: 'user', fullTextMatches: true, quoteMatches: text.includes(plan.quote), noteMatches: text.includes(plan.note) })
  }
  return { sessionId: plan.sessionId, capturedThroughSeq, expectedTextSHA256: signature(plan.expectedText), matchingUserMessages }
}

export function planRevisionEvidence(before, after) {
  if (!before || !after || !validId(before.sessionId) || before.sessionId !== after.sessionId || !Number.isSafeInteger(before.capturedThroughSeq) || before.capturedThroughSeq < -1 || !Number.isSafeInteger(after.capturedThroughSeq) || after.capturedThroughSeq < before.capturedThroughSeq || !/^[a-f0-9]{64}$/u.test(before.expectedTextSHA256) || before.expectedTextSHA256 !== after.expectedTextSHA256 || !Array.isArray(after.matchingUserMessages)) return { passed: false, reason: 'fixture-cut-or-identity-changed' }
  const matches = after.matchingUserMessages.filter(row => row?.type === 'user/message' && row.sourceKind === 'user' && Number.isSafeInteger(row.seq) && row.seq > before.capturedThroughSeq && row.seq <= after.capturedThroughSeq && row.fullTextMatches === true && row.quoteMatches === true && row.noteMatches === true)
  return { passed: matches.length === 1, sessionId: before.sessionId, beforeSeq: before.capturedThroughSeq, afterSeq: after.capturedThroughSeq, expectedTextSHA256: before.expectedTextSHA256, matchingUserMessageCount: matches.length, ...(matches.length === 1 ? { userMessageSeq: matches[0].seq } : {}) }
}

/** Invoke only behind the provider's owner + disposable-profile file binding. */
export async function readOwnedHarnessFeatureEvidence(services, binding, request) {
  assert.ok(request && ['archive', 'plan'].includes(request.kind), 'Unknown fixture evidence operation')
  if (request.kind === 'archive') {
    const workspace = services.workspaceRegistry.get(binding.workspaceId)
    return projectHarnessArchiveSnapshot(workspace, [...services.workspaceRegistry.archivedSessionIds], binding)
  }
  assert.ok(validId(binding?.plan?.sessionId), 'Plan fixture session is not bound')
  const surface = await services.sessionQuery.readSurface(binding.plan.sessionId)
  return projectHarnessPlanSnapshot(surface, binding)
}

/** Serializable Playwright canvas.evaluate callback. Wait for a future real draw receipt. */
export function waitForInlinePaint(canvas, { timeoutMs = 10000 } = {}) {
  return new Promise((resolve, reject) => {
    if (canvas?.tagName !== 'CANVAS' || canvas.id !== 'screen' || !Number.isSafeInteger(timeoutMs) || timeoutMs < 1 || timeoutMs > 20000) { reject(Error('Invalid inline paint observation')); return }
    const view = canvas.ownerDocument?.defaultView
    if (!view || typeof view.requestAnimationFrame !== 'function') { reject(Error('Inline render clock is unavailable')); return }
    let finished = false, rendering = false
    const finish = (error, value) => {
      if (finished) return; finished = true; clearTimeout(timer); canvas.removeEventListener('qiuya-preview-frame', painted)
      if (error) reject(error); else resolve(value)
    }
    const painted = event => {
      const frame = event.detail
      if (finished || rendering || event.target !== canvas || !frame || typeof frame.frameId !== 'string' || !frame.frameId.length || frame.frameId.length > 512 || /[\x00-\x1f\x7f]/u.test(frame.frameId) || !Number.isSafeInteger(frame.width) || frame.width <= 1 || !Number.isSafeInteger(frame.height) || frame.height <= 1 || canvas.width !== frame.width || canvas.height !== frame.height) return
      rendering = true
      view.requestAnimationFrame(() => view.requestAnimationFrame(() => {
        rendering = false
        if (finished || canvas.width !== frame.width || canvas.height !== frame.height || !canvas.getClientRects().length) return
        finish(null, { painted: true, frameId: frame.frameId, width: frame.width, height: frame.height, afterPaintEvent: true, postEventRenderTurns: 2 })
      }))
    }
    const timer = setTimeout(() => finish(Error('Inline preview did not publish a real painted frame')), timeoutMs)
    canvas.addEventListener('qiuya-preview-frame', painted)
  })
}
