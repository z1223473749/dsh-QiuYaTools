import { build } from 'esbuild'
import { readFile, mkdir, writeFile, cp } from 'node:fs/promises'
import { buildSessionWindowHelper } from '../src/features/session-windows/build-helper.mjs'
import { buildMacOSComputer } from './build-macos-computer.mjs'
import { createHash } from 'node:crypto'
import { createRequire } from 'node:module'
import { dirname, resolve } from 'node:path'
import { composerPreviewBuild } from './composer-preview-build.mjs'

const require = createRequire(import.meta.url)

const pkg = JSON.parse(await readFile(new URL('../package.json', import.meta.url), 'utf8'))
await import('./theme-assets.mjs')
await mkdir('lib', { recursive: true })
await mkdir('lib/smart-segmentation', { recursive: true })
await build({ entryPoints: ['src/client/smart-segmentation-worker.ts'], outfile: 'lib/smart-segmentation/worker.js', bundle: true, platform: 'browser', format: 'esm', target: 'es2022' })
for (const file of ['ort.wasm.min.mjs', 'ort-wasm-simd-threaded.mjs']) await cp(resolve('node_modules/onnxruntime-web/dist', file), resolve('lib/smart-segmentation', file))
await writeFile('lib/smart-segmentation/NOTICE.txt', 'ONNX Runtime Web 1.20.1 — Copyright (c) Microsoft Corporation. All rights reserved. MIT license: https://github.com/microsoft/onnxruntime/blob/v1.20.1/LICENSE\nSlimSAM quantized ONNX weights (downloaded on first use, not included in this package): Xenova/slimsam-77-uniform, revision 5850ab45f587c112167512ffef949107115e26a0, Apache-2.0. https://huggingface.co/Xenova/slimsam-77-uniform\n')
await build({
  entryPoints: ['src/index.ts'], outfile: 'lib/index.js', bundle: true,
  // Ship schema validation with the Host; installed/linked plugins cannot rely
  // on the development node_modules directory or a peer-resolution fallback.
  platform: 'node', target: 'node22', format: 'esm',
  // Keep all features and identifiers while leaving room for the self-contained
  // Windows runtime under the installer's existing 64 MiB archive limit.
  minifyWhitespace: true,
})
await build({ entryPoints: ['src/features/computer-use/remote.ts'], outfile: 'lib/computer-agent.js', bundle: true, platform: 'node', target: 'node22', format: 'esm', minifyWhitespace: true })
const client = await build({
  entryPoints: ['src/client/index.tsx'], bundle: true, write: false,
  outfile: 'lib/client.js',
  platform: 'browser', target: 'es2022', format: 'cjs',
  external: ['@deepseek-ai/*', 'react', 'react/*', 'react-dom', 'react-dom/*', 'node:*'],
  minifyWhitespace: true,
  jsx: 'automatic', loader: { '.css': 'text' },
  plugins: [composerPreviewBuild(), {
    name: 'qiuya-css-modules',
    setup(build) {
      build.onLoad({ filter: /\.module\.css$/ }, async ({ path }) => ({
        contents: await readFile(path, 'utf8'), loader: 'local-css',
      }))
    },
  }],
})
const source = client.outputFiles.find(file => file.path.endsWith('.js')).text
const styles = client.outputFiles.filter(file => file.path.endsWith('.css')).map(file => file.text).join('\n')
const wrapper = `// Generated by scripts/build.mjs. Shared modules come from the Harness loader.\nwindow.__ModuleLoader__.load({ id: ${JSON.stringify(pkg.name)}, factory(require) {\nvar module = { exports: {} }; var exports = module.exports;\nvar __QYT_BUNDLED_CSS__ = ${JSON.stringify(styles)};\n${source}\nreturn module.exports;\n} });\n`
await writeFile('lib/client.js', wrapper)
await mkdir('lib/third-party', { recursive: true })
for (const dependency of ['fflate', 'pdfjs-dist']) {
  await writeFile(`lib/third-party/${dependency}-LICENSE.txt`, await readFile(resolve(dirname(require.resolve(dependency)), '../LICENSE')))
}
await buildSessionWindowHelper(new URL('../lib/', import.meta.url))
await buildMacOSComputer()
if (process.platform === 'darwin') {
  const artifacts = []
  for (const file of ['QiuYaTools Sessions.app/Contents/MacOS/qiuya-session-window', 'QiuYaTools Computer.app/Contents/MacOS/qiuya-computer']) {
    const binary = await readFile(new URL(`../lib/${file}`, import.meta.url))
    artifacts.push({ file, bytes: binary.length, sha256: createHash('sha256').update(binary).digest('hex') })
  }
  await writeFile('lib/macos-manifest.json', JSON.stringify({ protocolVersion: 1, version: pkg.qiuyaNative?.version ?? pkg.version, artifacts }, null, 2) + '\n')
}
console.log(`Built ${pkg.name}@${pkg.version} (Host + Client)`)
