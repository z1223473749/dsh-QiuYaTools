import { build } from 'esbuild'
import { readFile, mkdir, writeFile } from 'node:fs/promises'
import { buildSessionWindowHelper } from '../src/features/session-windows/build-helper.mjs'

const pkg = JSON.parse(await readFile(new URL('../package.json', import.meta.url), 'utf8'))
const menuIcon = await readFile(new URL('../assets/icon-menu.png', import.meta.url))
const colorIcon = await readFile(new URL('../assets/icon-color.webp', import.meta.url))
const oceanScene = await readFile(new URL('../assets/q-ocean-scene.webp', import.meta.url))
await writeFile(new URL('../src/client/brand-assets.ts', import.meta.url), `// Generated from assets/ by scripts/build.mjs before bundling.\nexport const MONO_ICON_DATA_URL: string = ${JSON.stringify(`data:image/png;base64,${menuIcon.toString('base64')}`)}\nexport const COLOR_ICON_DATA_URL: string = ${JSON.stringify(`data:image/webp;base64,${colorIcon.toString('base64')}`)}\nexport const OCEAN_SCENE_DATA_URL: string = ${JSON.stringify(`data:image/webp;base64,${oceanScene.toString('base64')}`)}\n`)
await mkdir('lib', { recursive: true })
await build({
  entryPoints: ['src/index.ts'], outfile: 'lib/index.js', bundle: true,
  // Ship schema validation with the Host; installed/linked plugins cannot rely
  // on the development node_modules directory or a peer-resolution fallback.
  platform: 'node', target: 'node22', format: 'esm',
})
const client = await build({
  entryPoints: ['src/client/index.tsx'], bundle: true, write: false,
  outfile: 'lib/client.js',
  platform: 'browser', target: 'es2022', format: 'cjs', packages: 'external',
  jsx: 'automatic', loader: { '.css': 'text' },
  plugins: [{
    name: 'qiuya-css-modules',
    setup(build) {
      build.onLoad({ filter: /\.module\.css$/ }, async ({ path }) => ({
        contents: await readFile(path, 'utf8'), loader: 'local-css',
      }))
    },
  }],
})
const source = client.outputFiles.find(file => file.path.endsWith('.js')).text
const styles = client.outputFiles.filter(file => file.path.endsWith('.css')).map(file => file.text).join('\n')
const wrapper = `// Generated by scripts/build.mjs. Shared modules come from the Harness loader.\nwindow.__ModuleLoader__.load({ id: ${JSON.stringify(pkg.name)}, factory(require) {\nvar module = { exports: {} }; var exports = module.exports;\nvar __QYT_BUNDLED_CSS__ = ${JSON.stringify(styles)};\n${source}\nreturn module.exports;\n} });\n`
await writeFile('lib/client.js', wrapper)
await buildSessionWindowHelper(new URL('../lib/', import.meta.url))
console.log(`Built ${pkg.name}@${pkg.version} (Host + Client)`)
