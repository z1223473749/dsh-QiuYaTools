import test from 'node:test'
import assert from 'node:assert/strict'
import { execFile } from 'node:child_process'
import { promisify } from 'node:util'
import { fileURLToPath } from 'node:url'

// This compiles the actual native input boundary but runs only pure metadata
// and injected readiness backends: no GUI, AX request or native input is sent.
test('macOS exact-window readiness refuses same-process siblings and preserves cancellation/budgets without AX content', { skip: process.platform !== 'darwin', timeout: 120_000 }, async t => {
  const { stdout } = await promisify(execFile)(process.execPath, [fileURLToPath(new URL('../scripts/test-macos-computer.mjs', import.meta.url))], { timeout: 110_000, maxBuffer: 1_000_000 })
  assert.match(stdout, /exact-window CG metadata\/ambiguity\/front-order zero-post matrices/u)
  assert.match(stdout, /exact ordered-prefix\/destination-specific identity matrices/u)
  assert.match(stdout, /exact pointer route\/negative-screen\/zero-post matrices/u)
  assert.match(stdout, /strict AX keyboard-root\/non-key-sibling\/error\/drift matrices/u)
  assert.match(stdout, /per-post human-generation\/partial-input\/independent-UP matrices/u)
  assert.match(stdout, /bounded focus readiness\/human\/cancel\/epoch\/deadline matrices \(no real activation\/AX\/input\)/u)
  const pairLine = stdout.split('\n').find(line => line.startsWith('OwnedKeyboardPairDelivery pure matrix: '))
  assert.ok(pairLine, 'The actual compiled key-pair boundary must run its cancellation and release matrix')
  const pair = JSON.parse(pairLine.slice('OwnedKeyboardPairDelivery pure matrix: '.length))
  assert.equal(pair.passed, true)
  assert.equal(pair.caseCount, 14)
  assert.equal(pair.realSwiftTaskCancellation, true)
  assert.equal(pair.nativeInputEvents, 0)
  assert.equal(pair.livePIDReuseTested, false)
  assert.equal(pair.privateNativeReleaseRegistryTested, false)
  const recipientLine = stdout.split('\n').find(line => line.startsWith('OwnedKeyboardRecipientPolicy pure matrix: '))
  assert.ok(recipientLine)
  const recipient = JSON.parse(recipientLine.slice('OwnedKeyboardRecipientPolicy pure matrix: '.length))
  assert.equal(recipient.passed, true)
  assert.equal(recipient.cases, 12)
  assert.equal(recipient.nativeInputEvents, 0)
  assert.equal(recipient.livePIDReuseTested, false)
  const completionLine = stdout.split('\n').find(line => line.startsWith('CompletedKeyboardAction pure matrix: '))
  assert.ok(completionLine, 'The compiled completion boundary must run independently of AX readiness')
  const completion = JSON.parse(completionLine.slice('CompletedKeyboardAction pure matrix: '.length))
  assert.equal(completion.passed, true)
  assert.equal(completion.caseCount, 41)
  assert.equal(completion.realSwiftTaskCancellation, true)
  assert.equal(completion.nativeInputEvents, 0)
  assert.equal(completion.realAXReads, 0)
  assert.equal(completion.eventDeliveryAcknowledged, false)
  assert.equal(completion.livePIDReuseTested, false)
  assert.equal(completion.privateNativeReleaseRegistryTested, false)
  assert.ok(completion.cases.includes('completed-pair-accepts-AX-unavailable-but-next-down-refuses-zero-posts'))
  assert.ok(completion.cases.includes('completion-refuses-same-geometry-sibling'))
  assert.ok(completion.cases.includes('completion-checkpoint-3-refuses-owned-release'))
  const retryLine = stdout.split('\n').find(line => line.startsWith('KeyboardDownReadiness pure matrix: '))
  assert.ok(retryLine, 'The actual compiled new-down wait boundary must execute its finite retry matrix')
  const retry = JSON.parse(retryLine.slice('KeyboardDownReadiness pure matrix: '.length))
  assert.equal(retry.passed, true)
  assert.equal(retry.caseCount, 30)
  assert.equal(retry.sharedActionRetryBudgetMs, 500)
  assert.equal(retry.fullProofLimitMs, 60)
  assert.equal(retry.maximumYieldMs, 10)
  assert.equal(retry.realSwiftTaskCancellation, true)
  assert.equal(retry.nativeInputEvents, 0)
  assert.equal(retry.realAXReads, 0)
  assert.equal(retry.eventDeliveryAcknowledged, false)
  assert.ok(retry.cases.includes('retry-budget-is-shared-across-characters-no-renewal-no-replay'))
  assert.ok(retry.cases.includes('fresh-AX-reveals-sibling-focus-immediate-zero-down-refusal'))
  const terminalLine = stdout.split('\n').find(line => line.startsWith('KeyboardPostAwait pure matrix: '))
  assert.ok(terminalLine, 'The post-await terminal checkpoint must run independently of the prior AX proof')
  const terminal = JSON.parse(terminalLine.slice('KeyboardPostAwait pure matrix: '.length))
  assert.equal(terminal.passed, true)
  assert.equal(terminal.caseCount, 11)
  assert.equal(terminal.realSwiftTaskCancellation, true)
  assert.equal(terminal.nativeInputEvents, 0)
  assert.equal(terminal.realAXReads, 0)
  for (const kind of ['epoch', 'human', 'geometry', 'foreground', 'process-birth', 'owner', 'permission', 'owned-release']) {
    assert.ok(terminal.cases.includes('post-await-terminal-' + kind))
  }
  assert.match(stdout, /Dock window pure policy matrix: 9 cases/u)
  t.diagnostic('Actual Swift sources compiled; exact window and keyboard-root matrices, 14 key-pair/cancellation, 12 recipient-release, 41 completion, 30 bounded fresh-down readiness, 11 post-await terminal and 9 Dock policy cases passed. No GUI or native input; fake callbacks do not prove live PID reuse, the private release registry, target event-delivery ACKs, or a real Dock owner.')
})
